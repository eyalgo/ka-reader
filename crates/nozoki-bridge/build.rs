//! Writes `target/include/nozoki_bridge.h` from `src/exports.rs`.
//!
//! The header declares each `#[repr(C)]` struct and each exported `extern "C"` function the file
//! holds, through a small fixed type map. A type outside the map fails the build, so the header can
//! never quietly describe less than the source exports. The script adds no crate: it reads its own
//! crate's source by pattern, and `tests/exports.rs` is the backstop against a generator that drifts.
//!
//! The header goes to `<repository>/target/include/`, located from the manifest directory, which
//! assumes the default target directory (design § 3 A, *Artifacts*). It is never committed.

use std::fs;
use std::path::PathBuf;

const SOURCE: &str = "src/exports.rs";
const HEADER_BELOW_TARGET: &str = "include/nozoki_bridge.h";

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"));
    let header = manifest_dir.join("../../target").join(HEADER_BELOW_TARGET);

    // Re-run when the source changes and when the header does, so a hand edit never survives a build.
    println!("cargo:rerun-if-changed={SOURCE}");
    println!("cargo:rerun-if-changed={}", header.display());

    let source = fs::read_to_string(manifest_dir.join(SOURCE)).expect("src/exports.rs is readable");
    let text = render(&source);

    fs::create_dir_all(header.parent().expect("the header has a parent"))
        .expect("target/include is creatable");
    fs::write(&header, text).expect("the header is writable");
}

struct Struct {
    name: String,
    fields: Vec<(String, String)>,
}

struct Function {
    name: String,
    params: Vec<(String, String)>,
    returns: Option<String>,
}

fn render(source: &str) -> String {
    let structs = parse_structs(source);
    let known: Vec<&str> = structs.iter().map(|s| s.name.as_str()).collect();
    let functions = parse_functions(source);

    let mut out = String::from(
        "/* Generated by crates/nozoki-bridge/build.rs from src/exports.rs. Do not edit: a build rewrites it. */\n\
         #ifndef NOZOKI_BRIDGE_H\n#define NOZOKI_BRIDGE_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n",
    );
    for item in &structs {
        out.push_str(&format!("typedef struct {} {{\n", item.name));
        for (field, ty) in &item.fields {
            out.push_str(&format!("    {} {};\n", c_type(ty, &known), field));
        }
        out.push_str(&format!("}} {};\n\n", item.name));
    }
    for function in &functions {
        let params = if function.params.is_empty() {
            "void".to_string()
        } else {
            function
                .params
                .iter()
                .map(|(name, ty)| format!("{} {}", c_type(ty, &known), name))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let returns = function
            .returns
            .as_deref()
            .map_or("void".to_string(), |ty| c_type(ty, &known));
        out.push_str(&format!("{} {}({});\n", returns, function.name, params));
    }
    out.push_str("\n#endif\n");
    out
}

/// The fixed type map. Anything else fails the build.
fn c_type(rust: &str, known_structs: &[&str]) -> String {
    let rust = rust.trim();
    match rust {
        "*const c_char" => return "const char *".to_string(),
        "*mut u8" => return "uint8_t *".to_string(),
        "usize" => return "size_t".to_string(),
        _ => {}
    }
    for name in known_structs {
        if rust == format!("*mut {name}") {
            return format!("{name} *");
        }
        if rust == format!("*const {name}") {
            return format!("const {name} *");
        }
    }
    panic!(
        "nozoki-bridge build.rs: the Rust type `{rust}` is not in the header generator's type map"
    );
}

fn parse_structs(source: &str) -> Vec<Struct> {
    let lines: Vec<&str> = source.lines().map(str::trim).collect();
    let mut found = Vec::new();
    let mut index = 0;
    while index < lines.len() {
        let is_repr_c = lines[index] == "#[repr(C)]";
        let declaration = lines
            .get(index + 1)
            .and_then(|line| line.strip_prefix("pub struct "));
        if let (true, Some(rest)) = (is_repr_c, declaration) {
            let name = rest.trim_end_matches('{').trim().to_string();
            let mut fields = Vec::new();
            index += 2;
            while index < lines.len() && lines[index] != "}" {
                let field = lines[index].trim_end_matches(',');
                if let Some(field) = field.strip_prefix("pub ") {
                    let (field_name, ty) = field.split_once(':').unwrap_or_else(|| {
                        panic!("nozoki-bridge build.rs: cannot read the field `{field}`")
                    });
                    fields.push((field_name.trim().to_string(), ty.trim().to_string()));
                }
                index += 1;
            }
            found.push(Struct { name, fields });
        }
        index += 1;
    }
    found
}

fn parse_functions(source: &str) -> Vec<Function> {
    let lines: Vec<&str> = source.lines().map(str::trim).collect();
    let mut found = Vec::new();
    let mut index = 0;
    while index < lines.len() {
        let rest = lines[index]
            .strip_prefix("pub unsafe extern \"C\" fn ")
            .or_else(|| lines[index].strip_prefix("pub extern \"C\" fn "));
        if let Some(rest) = rest {
            let mut signature = rest.to_string();
            while !signature.contains('{') {
                index += 1;
                signature.push(' ');
                signature.push_str(lines.get(index).expect("a signature ends in `{`"));
            }
            let signature = signature
                .split('{')
                .next()
                .expect("split yields one part")
                .trim();
            found.push(parse_signature(signature));
        }
        index += 1;
    }
    found
}

fn parse_signature(signature: &str) -> Function {
    let (name, after_name) = signature
        .split_once('(')
        .unwrap_or_else(|| panic!("nozoki-bridge build.rs: no parameter list in `{signature}`"));
    let (params, after_params) = after_name.rsplit_once(')').unwrap_or_else(|| {
        panic!("nozoki-bridge build.rs: no closing parenthesis in `{signature}`")
    });
    let params = params
        .split(',')
        .map(str::trim)
        .filter(|param| !param.is_empty())
        .map(|param| {
            let (param_name, ty) = param.split_once(':').unwrap_or_else(|| {
                panic!("nozoki-bridge build.rs: cannot read the parameter `{param}`")
            });
            (param_name.trim().to_string(), ty.trim().to_string())
        })
        .collect();
    let returns = after_params
        .trim()
        .strip_prefix("->")
        .map(|ty| ty.trim().to_string());
    Function {
        name: name.trim().to_string(),
        params,
        returns,
    }
}
